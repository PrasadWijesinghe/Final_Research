// Turns the contract JSON Schemas (shared/contracts/schemas/) into src/types/contracts.gen.ts.
// Run through `npm run gen:types`, which writes the schemas first.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, "../../../shared/contracts/schemas");
const out = join(here, "../src/types/contracts.gen.ts");

// One combined schema so shared parts (Part, Expert, ...) are emitted once.
const defs = {};
const props = {};
for (const file of readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort()) {
  const { $defs = {}, $id, ...root } = JSON.parse(readFileSync(join(schemaDir, file), "utf8"));
  void $id;
  Object.assign(defs, $defs);
  const name = root.title;
  defs[name] = root;
  props[name] = { $ref: `#/$defs/${name}` };
}
const combined = { title: "Contracts", type: "object", properties: props, required: Object.keys(props), additionalProperties: false, $defs: defs };
const banner = "/* GENERATED by scripts/gen-types.mjs from shared/contracts. Do not edit; run `npm run gen:types`. */";
const ts = await compile(combined, "Contracts", { bannerComment: banner, additionalProperties: false, unreachableDefinitions: true, format: true });
writeFileSync(out, ts);
console.log(`wrote ${out}`);
